#!/usr/bin/env node
// Creates "Site Maintenance.app" in ~/Applications (Spotlight, Launchpad, Dock)
// plus an alias on the Desktop. Opening it starts the dashboard if it is not
// already running - through the background service when that is installed -
// and opens it in the default browser. It also handles claude-connector://
// links, so WP Admin's "Connect on this Mac" sets a site up in one click.
//
//   npm run shortcut              create / refresh it
//   npm run shortcut -- --remove  delete it again
import fs from 'fs';
import os from 'os';
import path from 'path';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const APP = path.join(os.homedir(), 'Applications', 'Site Maintenance.app');
const ALIAS = path.join(os.homedir(), 'Desktop', 'Site Maintenance.app');
const PORT = process.env.PORT || '4590';
const SERVICE = path.join(os.homedir(), 'Library', 'LaunchAgents', 'com.claude-connector.dashboard.plist');

if (process.platform !== 'darwin') {
  console.log('The shortcut is macOS only. Elsewhere run `npm start` in the dashboard folder and open http://127.0.0.1:4590');
  process.exit(1);
}

if (process.argv.includes('--remove')) {
  fs.rmSync(APP, { recursive: true, force: true });
  fs.rmSync(ALIAS, { force: true });
  console.log('Removed the Site Maintenance shortcut.');
  process.exit(0);
}

const sh = s => `'${String(s).replace(/'/g, `'\\''`)}'`;

// The work happens in a shell script inside the bundle. Its optional argument is
// a claude-connector:// link from WP Admin's "Connect on this Mac".
const launcher = `#!/bin/bash
# Site Maintenance launcher - generated by dashboard/shortcut.js
URL="http://127.0.0.1:${PORT}"
up() { curl -s -m 2 -o /dev/null "$URL/api/state"; }
if ! up; then
  if [ -f ${sh(SERVICE)} ]; then
    launchctl kickstart "gui/$(id -u)/com.claude-connector.dashboard" >/dev/null 2>&1 \\
      || launchctl bootstrap "gui/$(id -u)" ${sh(SERVICE)} >/dev/null 2>&1
  else
    mkdir -p ${sh(path.join(ROOT, 'data'))}
    cd ${sh(ROOT)} && PORT=${PORT} nohup ${sh(process.execPath)} server.js >> ${sh(path.join(ROOT, 'data', 'dashboard.log'))} 2>&1 &
  fi
  for i in $(seq 1 60); do up && break; sleep 0.25; done
fi
if ! up; then
  osascript -e 'display alert "Site Maintenance could not start" message "See dashboard/data/dashboard.log. Is Node.js still installed at ${process.execPath.replace(/"/g, '')}? Run npm run shortcut again after moving it."'
  exit 1
fi
case "$1" in
  claude-connector://*)
    # The dashboard picks the link up from the address and asks before connecting.
    open "$URL/#connect=$(${sh(process.execPath)} -e 'process.stdout.write(encodeURIComponent(process.argv[1]))' "$1")" ;;
  *) open "$URL" ;;
esac
`;

// An AppleScript applet rather than a bundle whose executable is the shell script:
// recent macOS refuses to open an unsigned script-executable bundle from Finder,
// and only an applet receives URL clicks ("open location"). Built here on this
// Mac, it is never quarantined, so Gatekeeper does not ask about it.
const applescript = `
on run
  do shell script quoted form of (POSIX path of (path to me) & "Contents/Resources/launch.sh") & " > /dev/null 2>&1 &"
end run

on open location theURL
  do shell script quoted form of (POSIX path of (path to me) & "Contents/Resources/launch.sh") & " " & quoted form of theURL & " > /dev/null 2>&1 &"
end open location
`;

const plistSet = (key, type, value) => {
  const plistFile = path.join(APP, 'Contents', 'Info.plist');
  try { execFileSync('plutil', ['-remove', key, plistFile], { stdio: 'ignore' }); } catch {}
  execFileSync('plutil', ['-insert', key, type, value, plistFile]);
};

fs.rmSync(APP, { recursive: true, force: true });
fs.mkdirSync(path.dirname(APP), { recursive: true });
const tmpScript = path.join(os.tmpdir(), `site-maintenance-${process.pid}.applescript`);
fs.writeFileSync(tmpScript, applescript);
execFileSync('osacompile', ['-o', APP, tmpScript]);
fs.rmSync(tmpScript, { force: true });
fs.writeFileSync(path.join(APP, 'Contents', 'Resources', 'launch.sh'), launcher, { mode: 0o755 });
plistSet('CFBundleIdentifier', '-string', 'com.claude-connector.dashboard.launcher');
plistSet('CFBundleName', '-string', 'Site Maintenance');
plistSet('CFBundleShortVersionString', '-string', JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version);
plistSet('LSUIElement', '-bool', 'true');
plistSet('CFBundleURLTypes', '-json', JSON.stringify([{ CFBundleURLName: 'Claude Connector site link', CFBundleURLSchemes: ['claude-connector'] }]));
// Use our .icns, not the applet's asset-catalog icon.
plistSet('CFBundleIconFile', '-string', 'applet');
try { execFileSync('plutil', ['-remove', 'CFBundleIconName', path.join(APP, 'Contents', 'Info.plist')], { stdio: 'ignore' }); } catch {}
fs.rmSync(path.join(APP, 'Contents', 'Resources', 'Assets.car'), { force: true });

// Icon: draw it in the browser the form test already uses, then build an .icns.
// A missing icon only means the generic one - never a failed install.
const ICON_SVG = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#3a6ff0"/><stop offset="1" stop-color="#1d48b8"/></linearGradient></defs>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#g)"/>
  <rect x="235" y="300" width="554" height="96" rx="30" fill="#fff" opacity=".28"/>
  <rect x="235" y="464" width="554" height="96" rx="30" fill="#fff" opacity=".28"/>
  <rect x="235" y="628" width="554" height="96" rx="30" fill="#fff" opacity=".28"/>
  <path d="M300 520l120 120 300-300" stroke="#fff" stroke-width="86" fill="none" stroke-linecap="round" stroke-linejoin="round"/>
</svg>`;
try {
  const { chromium } = await import('playwright-core');
  let b;
  for (const channel of ['chrome', 'msedge']) { try { b = await chromium.launch({ channel }); break; } catch {} }
  if (!b) b = await chromium.launch();
  const page = await b.newPage({ viewport: { width: 1024, height: 1024 } });
  await page.setContent(`<html><body style="margin:0;background:transparent">${ICON_SVG}</body></html>`);
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'cc-icon-'));
  const png = path.join(tmp, 'icon.png');
  await page.screenshot({ path: png, omitBackground: true });
  await b.close();
  const set = path.join(tmp, 'AppIcon.iconset');
  fs.mkdirSync(set);
  for (const n of [16, 32, 128, 256, 512]) {
    execFileSync('sips', ['-z', String(n), String(n), png, '--out', path.join(set, `icon_${n}x${n}.png`)], { stdio: 'ignore' });
    execFileSync('sips', ['-z', String(n * 2), String(n * 2), png, '--out', path.join(set, `icon_${n}x${n}@2x.png`)], { stdio: 'ignore' });
  }
  execFileSync('iconutil', ['-c', 'icns', set, '-o', path.join(APP, 'Contents', 'Resources', 'applet.icns')]);
  fs.rmSync(tmp, { recursive: true, force: true });
} catch (e) {
  console.log(`(Icon skipped: ${e.message.split('\n')[0]})`);
}

// Every change above invalidated the applet's signature: sign it again (ad hoc,
// for this Mac), then tell Launch Services the app handles claude-connector:// links.
execFileSync('codesign', ['--force', '--deep', '--sign', '-', APP], { stdio: 'ignore' });
try {
  execFileSync('/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister', ['-f', APP], { stdio: 'ignore' });
} catch {}
// Finder caches icons by path; touching the bundle makes it pick up the new one.
try { execFileSync('touch', [APP]); } catch {}

// A symlink rather than a Finder alias: making an alias needs permission to control Finder.
let alias = false;
if (!process.argv.includes('--no-desktop')) {
  try {
    fs.rmSync(ALIAS, { force: true });
    fs.symlinkSync(APP, ALIAS);
    alias = true;
  } catch {}
}

console.log(`Created ${APP}${alias ? '\nand an alias on the Desktop' : ''}.`);
console.log('Open it from Spotlight (⌘ Space → "Site Maintenance"), Launchpad or the Desktop; drag it to the Dock to keep it there.');
if (!fs.existsSync(SERVICE)) console.log('Tip: `npm run service:install` keeps the dashboard running in the background, so the morning form test runs without opening it.');
